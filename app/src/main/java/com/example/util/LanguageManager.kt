    fun get(key: String, language: AppLanguage): String {
        return strings[language]?.get(key)
            ?: strings[AppLanguage.ENGLISH]?.get(key)
            ?: strings[AppLanguage.ARABIC]?.get(key)
            ?: key
    }

    fun getFromContext(context: Context, key: String): String {
        val prefs = context.getSharedPreferences("app_settings", Context.MODE_PRIVATE)
        val langCode = prefs.getString("app_language", "ar") ?: "ar"
        val lang = AppLanguage.entries.find { it.code == langCode } ?: AppLanguage.ARABIC
        return get(key, lang)
    }

    fun applyLocale(context: Context, language: AppLanguage) {
        try {
            val locale = java.util.Locale(language.code)
            java.util.Locale.setDefault(locale)
            val config = context.resources.configuration
            config.setLocale(locale)
            config.setLayoutDirection(locale)
            context.resources.updateConfiguration(config, context.resources.displayMetrics)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }
}

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.ARABIC }

@Composable
fun AppLocalizationProvider(
    currentLanguage: AppLanguage,
    content: @Composable () -> Unit
) {
    val context = androidx.compose.ui.platform.LocalContext.current

    androidx.compose.runtime.LaunchedEffect(currentLanguage) {
        Translations.applyLocale(context, currentLanguage)
        (context as? android.app.Activity)?.window?.decorView?.layoutDirection =
            if (currentLanguage.direction == androidx.compose.ui.unit.LayoutDirection.Rtl) {
                android.view.View.LAYOUT_DIRECTION_RTL
            } else {
                android.view.View.LAYOUT_DIRECTION_LTR
            }
    }

    CompositionLocalProvider(
        LocalAppLanguage provides currentLanguage,
        androidx.compose.ui.platform.LocalLayoutDirection provides currentLanguage.direction,
        content = content
    )
}

@Composable
fun tr(key: String, fallback: String = ""): String {
    val currentLang = LocalAppLanguage.current
    val translated = Translations.get(key, currentLang)
    return if (translated == key && fallback.isNotBlank()) fallback else translated
}
